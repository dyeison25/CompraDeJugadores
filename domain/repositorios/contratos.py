from typing import Callable, Protocol
from domain.entidades import Usuario, Jugador, Compra


class UsuarioRepositorio(Protocol):
    def obtener(self, usuario_id: int) -> Usuario | None: ...
    def por_email(self, email: str) -> Usuario | None: ...
    def agregar(self, usuario: Usuario) -> Usuario: ...


class JugadorRepositorio(Protocol):
    def listar(self, incluir_vendidos: bool = False) -> list[Jugador]: ...
    def obtener(self, jugador_id: int) -> Jugador | None: ...
    def agregar(self, jugador: Jugador) -> Jugador: ...
    def actualizar(self, jugador: Jugador, version_esperada: int) -> Jugador: ...
    def eliminar(self, jugador_id: int, version_esperada: int) -> None: ...


class CompraRepositorio(Protocol):
    def registrar_atomica(self, jugador_id: int, preparar: Callable[[Jugador], Compra]) -> int:
        """Lee el jugador, aplica reglas y guarda compra/venta en una sola transacción."""
        ...
    def historial(self, usuario_id: int) -> list[Compra]: ...
    def resumen(self) -> dict: ...


class GestorClaves(Protocol):
    def generar(self, password: str) -> str: ...
    def verificar(self, password_hash: str, password: str) -> bool: ...
